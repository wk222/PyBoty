"""Micro-benchmarks reported in §Performance of the paper.

Three independent benchmarks, each printed as a small JSON line so the LaTeX
table can be regenerated by re-running this script.

Run from the repo root:
    python scripts/paper_benchmarks.py
"""

from __future__ import annotations

import json
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path


def percentile(values: list[float], pct: float) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    k = (len(s) - 1) * (pct / 100.0)
    f = int(k)
    c = min(f + 1, len(s) - 1)
    if f == c:
        return s[f]
    return s[f] + (s[c] - s[f]) * (k - f)


def bench_capability_bus(n_caps: int = 1000, n_lookups: int = 10_000) -> dict:
    from core.systems.capability.capability_bus import CapabilityBus
    from core.systems.capability.capability_bus_models import CapabilityLayer

    layers = list(CapabilityLayer)
    with tempfile.TemporaryDirectory() as tmp:
        bus = CapabilityBus(workspace_dir=tmp)
        for i in range(n_caps):
            bus.register(
                f"cap_{i}",
                layers[i % len(layers)],
                description=f"benchmark cap {i}",
                tags=[f"tag{i % 7}"],
            )
        latencies_us: list[float] = []
        for i in range(n_lookups):
            name = f"cap_{i % n_caps}"
            t0 = time.perf_counter()
            bus.get(name)
            latencies_us.append((time.perf_counter() - t0) * 1e6)
    return {
        "name": "capability_bus_lookup",
        "n_capabilities": n_caps,
        "n_lookups": n_lookups,
        "p50_us": round(percentile(latencies_us, 50), 2),
        "p95_us": round(percentile(latencies_us, 95), 2),
        "p99_us": round(percentile(latencies_us, 99), 2),
        "mean_us": round(statistics.mean(latencies_us), 2),
    }


def bench_architectural_guard_pytest(repeats: int = 3) -> dict:
    durations_s: list[float] = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        proc = subprocess.run(
            [
                sys.executable,
                "-m",
                "pytest",
                "tests/test_core_infrastructure.py",
                "-q",
                "-p",
                "no:cacheprovider",
            ],
            capture_output=True,
            cwd=str(Path(__file__).resolve().parents[1]),
            text=True,
        )
        durations_s.append(time.perf_counter() - t0)
        assert proc.returncode == 0, proc.stdout + proc.stderr
    return {
        "name": "architectural_guard_via_pytest",
        "repeats": repeats,
        "mean_s": round(statistics.mean(durations_s), 3),
        "min_s": round(min(durations_s), 3),
        "max_s": round(max(durations_s), 3),
    }


def bench_architectural_guard_pure(repeats: int = 5) -> dict:
    """Pure-algorithm cost: walk core/, parse with ast, count import edges."""
    import ast
    from pathlib import Path as _P

    root = _P(__file__).resolve().parents[1] / "core"
    py_files = [p for p in root.rglob("*.py") if "__pycache__" not in p.parts]
    durations_s: list[float] = []
    n_modules = 0
    n_edges = 0
    for r in range(repeats):
        n_modules = 0
        n_edges = 0
        t0 = time.perf_counter()
        for f in py_files:
            n_modules += 1
            try:
                tree = ast.parse(f.read_text(encoding="utf-8"))
            except SyntaxError:
                continue
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    n_edges += len(node.names)
                elif isinstance(node, ast.ImportFrom):
                    n_edges += max(1, len(node.names))
        durations_s.append(time.perf_counter() - t0)
    return {
        "name": "architectural_guard_pure_scan",
        "repeats": repeats,
        "n_modules": n_modules,
        "n_import_edges": n_edges,
        "mean_s": round(statistics.mean(durations_s), 3),
        "min_s": round(min(durations_s), 3),
        "max_s": round(max(durations_s), 3),
    }


def bench_memory_distill_assembly(n_facts: int = 60, n_diaries: int = 7, repeats: int = 1000) -> dict:
    facts = [
        f"- [{i % 3 + 1}\u2605] fact-{i}: deterministic content for benchmarking" for i in range(n_facts)
    ]
    diaries = [
        "\n".join(
            [
                f"## Diary {d}",
                "### preference",
                f"- user prefers option-{d}",
                "### decision",
                f"- decided to use approach-{d}",
                "### fact",
                f"- ambient fact recorded on day {d}",
            ]
        )
        for d in range(n_diaries)
    ]
    latencies_us: list[float] = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        prompt_parts = [
            "# Existing canonical memory",
            "\n".join(facts),
            "",
            "# Recent diaries",
            "\n\n".join(diaries),
        ]
        prompt = "\n".join(prompt_parts)
        _ = len(prompt)
        latencies_us.append((time.perf_counter() - t0) * 1e6)
    return {
        "name": "memdistill_prompt_assembly",
        "n_facts": n_facts,
        "n_diaries": n_diaries,
        "repeats": repeats,
        "p50_us": round(percentile(latencies_us, 50), 2),
        "p95_us": round(percentile(latencies_us, 95), 2),
        "mean_us": round(statistics.mean(latencies_us), 2),
    }


def main() -> None:
    results = [
        bench_capability_bus(),
        bench_memory_distill_assembly(),
        bench_architectural_guard_pure(),
        bench_architectural_guard_pytest(),
    ]
    for r in results:
        print(json.dumps(r, ensure_ascii=False))


if __name__ == "__main__":
    main()
